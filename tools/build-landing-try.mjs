/* tools/build-landing-try.mjs — the landing's "A trick, worked" card, cut from the stop's OWN working.

   The landing draws before the stops' code has loaded (tricks.js loadEngine, CLAUDE.md rule 30), and
   loading 240 KB of it just to show one worked example would break the first-load budget. So the
   example is cut here, at build time, from the real stop — its question, its steps, its first reason —
   into app/src/landing-try.js. test/light.mjs re-runs the stop and fails if this file has drifted:
   change the taster stop or its working → rerun `node tools/build-landing-try.mjs`. */
import { writeFileSync } from 'node:fs';
import { byId, example } from '../app/src/tricks.js';
import { tasterStop } from '../app/src/demo.js';

export function landingTry() {
  const t = byId[tasterStop()], q = example(t);
  return { id: t.id, title: t.title, text: q.text, steps: t.work(q).map((s) => ({ t: s.t, v: String(s.v) })), why: t.why[0] };
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const d = landingTry();
  writeFileSync(new URL('../app/src/landing-try.js', import.meta.url),
    `/* GENERATED by tools/build-landing-try.mjs from the stop's own work() — do not edit; test/light.mjs checks it. */\nexport const TRY = ${JSON.stringify(d, null, 1)};\n`);
  console.log(`landing-try: ${d.id} — ${d.steps.length} steps`);
}
